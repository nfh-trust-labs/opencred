function getVisual(schemaId?: string, isBlank?: boolean): SchemaVisual {
  if (isBlank) return BLANK_VISUAL;
  if (schemaId && ICONS[schemaId]) return ICONS[schemaId];
  return DEFAULT_VISUAL;
}

// ---------------------------------------------------------------------------
// Component
// ---------------------------------------------------------------------------

export function TemplateCard({ name, schemaId, isBlank, subtitle, onClick }: Props) {
  const v = getVisual(schemaId, isBlank);

  return (
    <button
      onClick={onClick}
      className="oc-template-card"
      style={
        {
          "--tc-border": v.border,
          ...(isBlank ? { borderStyle: "dashed" } : {}),
        } as React.CSSProperties
      }
    >
      <div className="oc-template-card-icon" style={{ backgroundColor: v.bg, color: v.fg }}>
        {v.icon}
      </div>
      <span className="oc-template-card-name">{name}</span>
      {subtitle && (
        <span
          style={{
            fontFamily: "var(--oc-font-mono)",
            fontSize: "0.6rem",
            color: "var(--oc-text-muted)",
            letterSpacing: "0.02em",
          }}
        >
          {subtitle}
        </span>
      )}
    </button>
  );
}

