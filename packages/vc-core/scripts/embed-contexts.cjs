/**
 * embed-contexts.cjs — Read JSON-LD context files and generate a TypeScript
 * module exporting them as typed objects.
 *
 * This eliminates the createRequire + require("*.json") pattern, making the
 * package compatible with bundlers (esbuild, webpack, rollup).
 *
 * Runs as part of the build step, before tsc.
 */

const fs = require("fs");
const path = require("path");

const contextsDir = path.resolve(__dirname, "..", "src", "contexts");
const outFile = path.resolve(__dirname, "..", "src", "context-data.ts");

const jsonFiles = fs.readdirSync(contextsDir).filter((f) => f.endsWith(".json")).sort();

if (jsonFiles.length === 0) {
  console.error("[embed-contexts] No JSON files found in", contextsDir);
  process.exit(1);
}

const lines = [
  "// Auto-generated by scripts/embed-contexts.cjs — do not edit manually.",
  "// Edit the JSON files in src/contexts/ and run the build.",
  "",
];

for (const file of jsonFiles) {
  const content = fs.readFileSync(path.join(contextsDir, file), "utf-8");
  // Validate it's valid JSON
  JSON.parse(content);
  // Convert filename to camelCase: "credentials-v2.json" → "credentialsV2"
  const name = file
    .replace(".json", "")
    .replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  lines.push(`export const ${name}: Record<string, unknown> = ${content.trim()};`);
  lines.push("");
}

fs.writeFileSync(outFile, lines.join("\n"));
console.log(`[embed-contexts] Generated ${outFile} with ${jsonFiles.length} contexts`);
